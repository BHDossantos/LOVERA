"use client";

import { use } from "react";
import { ApiError } from "@/lib/api";
import { useRequireMember } from "@/lib/auth";
import { AppShell } from "@/components/shell/AppShell";
import { Card, ErrorState, LinkButton, MatchReason } from "@/components/ui";
import { CorrectionForm } from "@/components/introductions/CorrectionForm";
import { IntroductionHeader } from "@/components/introductions/IntroductionHeader";
import { IntroductionLoading, IntroductionUnavailable } from "@/components/introductions/IntroductionStates";
import { DATA_CATEGORY_LABEL } from "@/components/introductions/types";
import { useExplanationViewed, useIntroduction } from "@/components/introductions/useIntroduction";

const SECTIONS = ["reasons", "data_categories"];

/** I02 Why this person: three plain-language reasons with evidence labels, data categories, provenance and a correction path. */
export default function WhyPage({ params }: { params: Promise<{ id: string }> }) {
  const { id } = use(params);
  const { me } = useRequireMember();
  const q = useIntroduction(me ? id : "");
  const intro = q.data;
  const ex = intro?.explanation ?? null;
  useExplanationViewed(id, SECTIONS, !!ex);

  return (
    <AppShell>
      {q.isLoading && <IntroductionLoading />}
      {q.isError && <ErrorState error={q.error as ApiError} retry={() => q.refetch()} />}
      {intro && !intro.profile && <IntroductionUnavailable passed={intro.status === "you_passed"} />}
      {intro && intro.profile && (
        <>
          <IntroductionHeader intro={intro} active="why" />
          <div className="space-y-4">
            <section aria-labelledby="reasons">
              <h2 id="reasons" className="text-lg font-bold text-ink">
                Three reasons, in plain language
              </h2>
              <p className="mb-3 mt-1 text-sm text-ink-secondary">Evidence labels say how sure we are. We never turn compatibility into a number.</p>
              {ex && ex.reasons.length > 0 ? (
                <ul className="space-y-2">
                  {ex.reasons.slice(0, 3).map((r, i) => (
                    <MatchReason key={`${r.label}-${i}`} label={r.label} strength={r.strength} text={r.text} />
                  ))}
                </ul>
              ) : (
                <Card>
                  <p className="text-ink-secondary">The explanation is still under concierge review. It will appear here before you need to decide.</p>
                </Card>
              )}
            </section>
            {ex && (
              <Card as="section" aria-labelledby="data-used">
                <h2 id="data-used" className="font-semibold text-ink">
                  What this was based on
                </h2>
                <ul className="mt-2 flex flex-wrap gap-2" aria-label="Data categories used">
                  {ex.data_categories.map((c) => (
                    <li key={c} className="rounded-full bg-surface-muted px-3 py-1 text-sm text-ink">
                      {DATA_CATEGORY_LABEL[c] ?? c.replace(/_/g, " ")}
                    </li>
                  ))}
                </ul>
                <p className="mt-3 text-xs text-ink-tertiary">Never used: identity documents, biometrics, precise location, private messages, safety reports or appeal material.</p>
                <dl className="mt-3 text-xs text-ink-tertiary">
                  <div className="flex gap-2">
                    <dt>Generated by</dt>
                    <dd className="font-mono">{ex.generator_version}</dd>
                  </div>
                  <div className="flex gap-2">
                    <dt>Reviewed by a person</dt>
                    <dd>{(ex as { reviewed?: boolean }).reviewed ? "Yes" : "Pending"}</dd>
                  </div>
                </dl>
              </Card>
            )}
            <div className="flex flex-col gap-2 sm:flex-row">
              <LinkButton href={`/introductions/${intro.id}/considerations`} fullWidth>
                See the friction and the unknown
              </LinkButton>
              {intro.status === "offered" && (
                <LinkButton href={`/introductions/${intro.id}/decision`} variant="secondary" fullWidth>
                  Decide now
                </LinkButton>
              )}
            </div>
            {intro.actions.can_correct && <CorrectionForm introId={intro.id} suggestedKeys={ex?.unknown.missing_signal_keys ?? []} />}
          </div>
        </>
      )}
    </AppShell>
  );
}
